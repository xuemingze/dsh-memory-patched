function parseSettings(source) {
	let value;
	try {
		value = parse(source);
	} catch (cause) {
		throw new TypeError("Memory consolidation settings are not valid YAML", { cause });
	}
	if (value === null || typeof value !== "object" || Array.isArray(value)) throw new TypeError("Memory consolidation settings must be an object");
	const record = value;
	const keys = Object.keys(record).sort().join(",");
	if (record.format === 1 && keys === "format,model,provider") return {
		selection: validateSelection({
			provider: record.provider,
			model: record.model
		}),
		debugEnabled: false,
		dedupe: "merge",
		writeGate: "on",
		forgetting: "shadow",
		dream: "shadow"
	};
	if (record.format !== SETTINGS_FORMAT || ![
		"debug,format,model,provider",
		"debug,dedupe,format,model,provider",
		"candidates,debug,dedupe,format,model,provider",
		"candidates,debug,dedupe,dream,forgetting,format,model,provider"
	].includes(keys)) throw new TypeError("Memory consolidation settings have missing or unknown fields");
	return {
		selection: validateSelection({
			provider: record.provider,
			model: record.model
		}),
		debugEnabled: validateDebugEnabled(record.debug),
		dedupe: coerceDedupeMode(record.dedupe),
		writeGate: coerceWriteGate(record.candidates),
		forgetting: coerceForgettingMode(record.forgetting),
		dream: coerceDreamMode(record.dream)
	};
}
