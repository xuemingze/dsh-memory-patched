/** Manual consolidation orchestration across preparation, worker, receipt, and commit. */
/** Keep the review lock across the worker run and final commit barrier. */
var SessionConsolidationRunner = class {
	consolidator;
	worker;
	receipts;
	commits;
	replay;
	memory;
	debug;
	constructor(consolidator, worker, receipts, commits, replay, memory, debug) {
		this.consolidator = consolidator;
		this.worker = worker;
		this.receipts = receipts;
		this.commits = commits;
		this.replay = replay;
		this.memory = memory;
		this.debug = debug;
	}
	async run(sessionId, signal) {
		const pending = this.receipts.listCommittingBySourceSession(sessionId)[0];
		if (pending !== void 0) return this.recoverPending(pending, signal);
		const input = await this.consolidator.prepare(sessionId, signal);
		return this.receipts.withReviewLock(input.reviewId, async () => {
			const existing = this.receipts.read(input.reviewId);
			if (existing?.state === "committed" || existing?.state === "no-change") return {
				outcome: existing.state,
				recovered: true,
				receipt: existing
			};
			if (existing?.state === "committing") {
				const attempt = existing.attempts.at(-1);
				if (attempt === void 0 || attempt.workerSessionId === null) throw new SessionConsolidationRunError("pending-recovery", "committing receipt has no worker attempt");
				const plan = await this.replay.loadPlan(attempt.workerSessionId, input, signal);
				return this.commits.commitWithinReviewLock({
					input,
					plan,
					attempt: attempt.attempt,
					workerSessionId: attempt.workerSessionId,
					workerConfig: {
						provider: attempt.provider,
						model: attempt.model
					},
					...signal === void 0 ? {} : { signal }
				});
			}
			const attempt = nextAttempt(existing);
			const workerSessionId = workerSessionIdOf(input.reviewId, attempt);
			const workerConfig = { ...this.worker.config };
			const debugIdentity = {
				reviewId: input.reviewId,
				attempt
			};
			this.debug?.record(debugIdentity, "runner-attempt", {
				sourceSessionId: input.source.sessionId,
				provider: workerConfig.provider,
				model: workerConfig.model
			});
			if (input.source.evidence.length === 0) {
				const plan = this.consolidator.planProposal(input, {
					outcome: "no-change",
					changes: []
				});
				return this.commits.commitWithinReviewLock({
					input,
					plan,
					attempt,
					workerSessionId: null,
					workerConfig,
					...signal === void 0 ? {} : { signal }
				});
			}
			try {
				const produced = await this.worker.run(input, attempt, signal);
				if (produced.workerSessionId !== workerSessionId) throw new SessionConsolidationRunError("worker-mismatch", "worker returned an unexpected Session id");
				try {
					return await this.commits.commitWithinReviewLock({
						input,
						plan: produced.plan,
						attempt,
						workerSessionId,
						workerConfig,
						...signal === void 0 ? {} : { signal }
					});
				} catch (error) {
					if (this.receipts.read(input.reviewId)?.state === "committing" || error instanceof SessionConsolidationError) throw error;
					throw new SessionConsolidationRunError("commit-failed", "consolidation commit failed before durable intent");
				}
			} catch (error) {
				const current = this.receipts.read(input.reviewId);
				if (current?.state === "committing") throw error;
				const state = classifyFailure(error, signal);
				this.debug?.failure(debugIdentity, `runner-${state}`, error);
				const receipt = createFailedConsolidationReceipt({
					input,
					attempt,
					workerSessionId,
					workerConfig,
					state
				}, this.receipts.timestamp(), current ?? existing);
				this.receipts.write(receipt);
				return {
					outcome: state,
					recovered: false,
					receipt
				};
			}
		});
	}
	recoverPending(pending, signal) {
		return this.receipts.withReviewLock(pending.reviewId, async () => {
			signal?.throwIfAborted();
			const receipt = this.receipts.read(pending.reviewId);
			if (receipt === void 0) throw new SessionConsolidationRunError("pending-recovery", "pending receipt disappeared");
			if (receipt.state === "committed" || receipt.state === "no-change" || receipt.state === "target-conflict") return {
				outcome: receipt.state,
				recovered: true,
				receipt
			};
			if (receipt.state !== "committing") throw new SessionConsolidationRunError("pending-recovery", "pending receipt changed to a non-recoverable state");
			const attempt = receipt.attempts.at(-1);
			if (attempt?.workerSessionId === void 0 || attempt.workerSessionId === null) throw new SessionConsolidationRunError("pending-recovery", "committing receipt has no worker Session");
			const target = this.memory.workspaceTargetForKey(receipt.workspaceKey);
			const workspace = await this.memory.readWorkspace(target);
			const plan = await this.replay.loadRecoveryPlan(attempt.workerSessionId, receipt, workspace, signal);
			return this.commits.recoverReceiptWithinReviewLock(receipt, target, plan);
		});
	}
};
