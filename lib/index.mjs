/** Respect the selected model's adapter-owned output cap while retaining a plugin cost ceiling. */
async function resolveConsolidationOutputTokens(llm, selection, ceiling, signal) {
	if (!Number.isSafeInteger(ceiling) || ceiling < 1) throw new TypeError("consolidation output-token ceiling must be a positive safe integer");
	const modelLimit = (await llm.resolveModelInfo(selection.provider, selection.model, signal)).defaultMaxTokens;
	if (modelLimit === void 0) return ceiling;
	if (!Number.isSafeInteger(modelLimit) || modelLimit < 1) throw new TypeError("DSH model output-token limit must be a positive safe integer");
	return Math.min(ceiling, modelLimit);
}
function parseSettings(source) {
	let value;
	try {
		value = parse(source);
	} catch (cause) {
		throw new TypeError("Memory consolidation settings are not valid YAML", { cause });
	}
	if (value === null || typeof value !== "object" || Array.isArray(value)) throw new TypeError("Memory consolidation settings must be an object");
	const record = value;
	const keys = Object.keys(record).sort().join(",");
	if (record.format === 1 && keys === "format,model,provider") return {
		selection: validateSelection({
			provider: record.provider,
			model: record.model
		}),
		debugEnabled: false
	};
	if (record.format !== SETTINGS_FORMAT || keys !== "debug,format,model,provider") throw new TypeError("Memory consolidation settings have missing or unknown fields");
	return {
		selection: validateSelection({
			provider: record.provider,
			model: record.model
		}),
		debugEnabled: validateDebugEnabled(record.debug)
	};
}
function validateSelection(value) {
	if (typeof value.provider !== "string" || value.provider.trim() === "" || /[\r\n]/u.test(value.provider)) throw new TypeError("consolidation provider must be a non-empty single line");
	if (typeof value.model !== "string" || value.model.trim() === "" || /[\r\n]/u.test(value.model)) throw new TypeError("consolidation model must be a non-empty single line");
	return {
		provider: value.provider,
		model: value.model
	};
}
function validateDebugEnabled(value) {
	if (typeof value !== "boolean") throw new TypeError("consolidation debug must be a boolean");
	return value;
}
function serializeSettings(settings) {
	return stringify({
		format: SETTINGS_FORMAT,
		provider: settings.selection.provider,
		model: settings.selection.model,
		debug: settings.debugEnabled
	}, { lineWidth: 0 });
}
function settingsRevision(settings) {
	return `sha256:${createHash("sha256").update(serializeSettings(settings), "utf8").digest("hex")}`;
}
function safeDiagnosticMessage(error) {
	return (error instanceof Error ? error.message : String(error)).replace(/(?:sk|key|token)-[A-Za-z0-9._-]{8,}/gu, "[REDACTED]").replace(/[\r\n]+/gu, " ").trim() || "model catalog failed";
}
