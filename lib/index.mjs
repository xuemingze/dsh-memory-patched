function createMemoryUpdateTool(store, observations) {
	return defineTool({
		name: "memory_update",
		description: "Replace Global memory or atomically update current-Workspace Markdown memory. The Host manages concurrency; never inspect or calculate revisions.",
		parameters: { change: {
			required: true,
			oneOf: [{
				type: "object",
				additionalProperties: false,
				properties: {
					action: {
						type: "string",
						const: "replace_global",
						required: true
					},
					content: {
						type: "string",
						required: true
					}
				}
			}, {
				type: "object",
				additionalProperties: false,
				properties: {
					action: {
						type: "string",
						const: "update_workspace",
						required: true
					},
					changes: {
						type: "array",
						required: true,
						description: "One atomic batch. Put full records and place deletes before puts.",
						items: { oneOf: [{
							type: "object",
							additionalProperties: false,
							properties: {
								action: {
									type: "string",
									const: "put",
									required: true
								},
								name: {
									type: "string",
									required: true
								},
								description: {
									type: "string",
									required: true
								},
								type: {
									type: "string",
									enum: [
										"feedback",
										"project",
										"reference"
									],
									required: true
								},
								content: {
									type: "string",
									required: true
								}
							}
						}, {
							type: "object",
							additionalProperties: false,
							properties: {
								action: {
									type: "string",
									const: "delete",
									required: true
								},
								name: {
									type: "string",
									required: true
								}
							}
						}] }
					}
				}
			}]
		} },
		output: {
			schema: {
				type: "object",
				additionalProperties: false,
				properties: {
					status: {
						type: "string",
						const: "committed",
						required: true
					},
					scope: {
						type: "string",
						enum: ["global", "workspace"],
						required: true
					},
					change_count: {
						type: "integer",
						required: true
					}
				}
			},
			render: (_args, value) => [{
				type: "text",
				text: JSON.stringify(value)
			}]
		},
		async execute(args, exec) {
			const change = args.change;
			const agent = exec.agent;
			if (change.action === "replace_global") {
				const expectedRevision = observations.requireGlobal(agent);
				try {
					const result = await store.commitGlobal({
						expectedRevision,
						content: change.content
					});
					observations.advanceGlobal(agent, expectedRevision, result.revision);
					return {
						status: "committed",
						scope: "global",
						change_count: 1
					};
				} catch (error) {
					MemoryObservationRegistry.modelFacingError(error);
				}
			}
			const cwd = agent?.session.header.cwd;
			if (cwd === void 0) throw new Error("workspace memory requires a Session cwd");
			const scope = store.scopeForCwd(cwd);
			const expectedRevision = observations.requireWorkspace(agent, scope);
			const changes = change.changes.map((item) => item.action === "put" ? {
				action: "put",
				record: {
					name: item.name,
					description: item.description,
					type: item.type,
					content: item.content
				}
			} : {
				action: "delete",
				name: item.name
			});
			try {
				const result = await store.commitWorkspace({
					scope,
					expectedRevision,
					changes
				});
				observations.advanceWorkspace(agent, scope, expectedRevision, result.revision);
				return {
					status: "committed",
					scope: "workspace",
					change_count: changes.length
				};
			} catch (error) {
				MemoryObservationRegistry.modelFacingError(error);
			}
		}
	});
}
async function handleMemoryRpc(store, getSessionCatalog, getSessionRunner, getLlmCatalog, getSessionWorker, consolidationSettings, endpoint, payload, signal) {
	if (signal.aborted) return cancelled(signal);
	try {
		switch (endpoint) {
			case "status":
				parseEmptyPayload(payload);
				return {
					ok: true,
					value: parseMemoryStatus(store.status())
				};
			case "global/read":
				parseEmptyPayload(payload);
				return {
					ok: true,
					value: parseGlobalMemoryView(await store.readGlobal())
				};
			case "global/replace": {
				const input = parseGlobalReplacePayload(payload);
				try {
					return {
						ok: true,
						value: parseGlobalReplaceResponse({
							status: "committed",
							revision: (await store.commitGlobal(input)).revision
						})
					};
				} catch (error) {
					if (error instanceof MemoryConflictError) return {
						ok: true,
						value: parseGlobalReplaceResponse({
							status: "conflict",
							currentRevision: error.currentRevision
						})
					};
					throw error;
				}
			}
			case "workspaces/list":
				parseEmptyPayload(payload);
				return {
					ok: true,
					value: parseWorkspaceListResponse(store.listWorkspaces())
				};
			case "workspace/read": {
				const input = parseWorkspaceReadPayload(payload);
				const workspace = store.readWorkspaceById(input.workspaceId);
				if (workspace === void 0) return badRequest(`unknown Workspace id: ${input.workspaceId}`);
				return {
					ok: true,
					value: parseWorkspaceReadResponse(workspace)
				};
			}
			case "workspace/commit": {
				const input = parseWorkspaceCommitPayload(payload);
				try {
					const result = await store.commitWorkspaceById(input);
					if (result === void 0) return badRequest(`unknown Workspace id: ${input.workspaceId}`);
					return {
						ok: true,
						value: parseWorkspaceCommitResponse({
							status: "committed",
							revision: result.revision
						})
					};
				} catch (error) {
					if (error instanceof MemoryConflictError) return {
						ok: true,
						value: parseWorkspaceCommitResponse({
							status: "conflict",
							currentRevision: error.currentRevision
						})
					};
					throw error;
				}
			}
			case "sessions/list": {
				parseEmptyPayload(payload);
				const catalog = getSessionCatalog();
				return {
					ok: true,
					value: parseSessionListResponse(catalog === void 0 ? {
						available: false,
						sessions: []
					} : await catalog.list(signal))
				};
			}
			case "sessions/consolidate": {
				const input = parseSessionConsolidatePayload(payload);
				const runner = getSessionRunner();
				if (runner === void 0) return badRequest("Session consolidation is unavailable in this Host profile");
				const debugLoggingEnabled = consolidationSettings.read().debugEnabled;
				const result = await runner.run(input.sessionId, signal);
				const latestAttempt = result.receipt.attempts.at(-1)?.attempt ?? 0;
				return {
					ok: true,
					value: parseSessionConsolidateResponse({
						status: result.outcome,
						recovered: result.recovered,
						reviewId: result.receipt.reviewId,
						attempt: latestAttempt,
						changeCount: result.receipt.changes.length,
						debugLoggingEnabled
					})
				};
			}
			case "models/read": {
				parseEmptyPayload(payload);
				const llm = getLlmCatalog();
				if (llm === void 0) {
					const current = consolidationSettings.read();
					return {
						ok: true,
						value: parseConsolidationModelCatalogResponse({
							available: false,
							selection: current.selection,
							debugEnabled: current.debugEnabled,
							revision: current.revision,
							providers: [],
							failures: []
						})
					};
				}
				return {
					ok: true,
					value: parseConsolidationModelCatalogResponse(await readConsolidationModelCatalog(llm, consolidationSettings))
				};
			}
			case "models/select": {
				const input = parseConsolidationModelSelectPayload(payload);
				const current = consolidationSettings.read();
				const selection = {
					provider: input.provider,
					model: input.model
				};
				if (selection.provider !== current.selection.provider || selection.model !== current.selection.model) {
					const llm = getLlmCatalog();
					if (llm === void 0) return badRequest("DSH model catalog is unavailable in this Host profile");
					if (!selectionIsAvailable(await readConsolidationModelCatalog(llm, consolidationSettings), selection)) return badRequest(`model route is not active: ${input.provider}/${input.model}`);
				}
				const result = consolidationSettings.commit({
					expectedRevision: input.expectedRevision,
					selection,
					debugEnabled: input.debugEnabled
				});
				if (result.status === "committed") getSessionWorker()?.updateModel(selection);
				return {
					ok: true,
					value: parseConsolidationModelSelectResponse(result)
				};
			}
			default: return badRequest(`unknown memory endpoint: ${endpoint}`);
		}
	} catch (error) {
		if (signal.aborted) return cancelled(signal);
		if (error instanceof TypeError || error instanceof MemoryValidationError || error instanceof SessionConsolidationError) return badRequest(error.message);
		return {
			ok: false,
			error: {
				code: "internal",
				message: error instanceof Error ? error.message : String(error),
				details: {}
			}
		};
	}
}
function badRequest(message) {
	return {
		ok: false,
		error: {
			code: "bad-request",
			message,
			details: { issues: [{
				code: "custom",
				path: [],
				message
			}] }
		}
	};
}
function cancelled(signal) {
	return {
		ok: false,
		error: {
			code: "cancelled",
			message: signal.reason instanceof Error ? signal.reason.message : "cancelled",
			details: {}
		}
	};
}
