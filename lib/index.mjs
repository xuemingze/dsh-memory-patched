/** Binds prompt-time memory generations to live Agent identity. */
var MemoryObservationRegistry = class {
	store;
	observations = /* @__PURE__ */ new WeakMap();
	constructor(store) {
		this.store = store;
	}
	/** Render model-visible memory while retaining its Host-only CAS generations. */
	render(agent) {
		const snapshot = this.store.renderContextSnapshot(agent?.session.header.cwd);
		if (agent !== void 0) this.observations.set(agent, {
			globalRevision: snapshot.globalRevision,
			...snapshot.workspace === void 0 ? {} : { workspace: snapshot.workspace }
		});
		return snapshot.text;
	}
	requireGlobal(agent) {
		return this.require(agent).globalRevision;
	}
	requireWorkspace(agent, scope) {
		const workspace = this.require(agent).workspace;
		if (workspace === void 0 || workspace.key !== scope.key) throw new MemoryObservationError("Current Workspace memory was not present in this Agent context.");
		return workspace.revision;
	}
	advanceGlobal(agent, expected, next) {
		const current = this.observations.get(agent);
		if (current?.globalRevision !== expected) return;
		this.observations.set(agent, {
			...current,
			globalRevision: next
		});
	}
	advanceWorkspace(agent, scope, expected, next) {
		const current = this.observations.get(agent);
		if (current?.workspace?.key !== scope.key || current.workspace.revision !== expected) return;
		this.observations.set(agent, {
			...current,
			workspace: {
				key: scope.key,
				revision: next
			}
		});
	}
	/** Hide opaque revisions while preserving a useful model-facing conflict. */
	static modelFacingError(error) {
		if (error instanceof MemoryConflictError) throw new MemoryObservationError("Memory changed after this Agent read it. Review the refreshed memory context before updating again.");
		throw error;
	}
	require(agent) {
		if (agent === void 0) throw new MemoryObservationError("memory_update requires an active Agent with an observed Memory Context.");
		const observation = this.observations.get(agent);
		if (observation === void 0) throw new MemoryObservationError("memory_update requires Memory Context to be assembled before the write.");
		return observation;
	}
};
