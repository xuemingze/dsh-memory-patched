/** Manual consolidation orchestration across preparation, worker, receipt, and commit. */
/** Keep the review lock across the worker run and final commit barrier. */
var SessionConsolidationRunner = class {
	consolidator;
	worker;
	receipts;
	commits;
	replay;
	memory;
	debug;
	candidatePool;
	constructor(consolidator, worker, receipts, commits, replay, memory, debug, candidatePool) {
		this.consolidator = consolidator;
		this.worker = worker;
		this.receipts = receipts;
		this.commits = commits;
		this.replay = replay;
		this.memory = memory;
		this.debug = debug;
		this.candidatePool = candidatePool;
	}
	async run(sessionId, signal) {
		const pending = this.receipts.listCommittingBySourceSession(sessionId)[0];
		if (pending !== void 0) return this.recoverPending(pending, signal);
		const input = await this.consolidator.prepare(sessionId, signal);
		return this.receipts.withReviewLock(input.reviewId, async () => {
			const existing = this.receipts.read(input.reviewId);
			if (existing?.state === "committed" || existing?.state === "no-change") return {
				outcome: existing.state,
				recovered: true,
				receipt: existing
			};
			if (existing?.state === "committing") {
				const attempt = existing.attempts.at(-1);
				if (attempt === void 0 || attempt.workerSessionId === null) throw new SessionConsolidationRunError("pending-recovery", "committing receipt has no worker attempt");
				const plan = await this.replay.loadPlan(attempt.workerSessionId, input, signal);
				const result = await this.commits.commitWithinReviewLock({
					input,
					plan,
					attempt: attempt.attempt,
					workerSessionId: attempt.workerSessionId,
					workerConfig: {
						provider: attempt.provider,
						model: attempt.model
					},
					...signal === void 0 ? {} : { signal }
				});
				if (result.outcome === "committed" || result.outcome === "no-change") this.settleCandidates(input.workspace.scope.key, plan, input.pendingCandidates);
				return result;
			}
			const attempt = nextAttempt(existing);
			const workerSessionId = workerSessionIdOf(input.reviewId, attempt);
			const workerConfig = { ...this.worker.config };
			const debugIdentity = {
				reviewId: input.reviewId,
				attempt
			};
			this.debug?.record(debugIdentity, "runner-attempt", {
				sourceSessionId: input.source.sessionId,
				provider: workerConfig.provider,
				model: workerConfig.model
			});
			if (input.source.evidence.length === 0) {
				const plan = this.consolidator.planProposal(input, {
					outcome: "no-change",
					changes: []
				});
				const result = await this.commits.commitWithinReviewLock({
					input,
					plan,
					attempt,
					workerSessionId: null,
					workerConfig,
					...signal === void 0 ? {} : { signal }
				});
				if (result.outcome === "committed" || result.outcome === "no-change") this.settleCandidates(input.workspace.scope.key, plan, input.pendingCandidates);
				return result;
			}
			try {
				const produced = await this.worker.run(input, attempt, signal);
				if (!isWorkerSessionOf(produced.workerSessionId, workerSessionId)) throw new SessionConsolidationRunError("worker-mismatch", "worker returned an unexpected Session id");
				if (produced.plan.staleChanges !== void 0) this.debug?.record(debugIdentity, "temporal-guard", { stale: produced.plan.staleChanges });
				try {
					const result = await this.commits.commitWithinReviewLock({
						input,
						plan: produced.plan,
						attempt,
						workerSessionId: produced.workerSessionId,
						workerConfig,
						...signal === void 0 ? {} : { signal }
					});
					if (result.outcome === "committed" || result.outcome === "no-change") this.settleCandidates(input.workspace.scope.key, produced.plan, input.pendingCandidates);
					return result;
				} catch (error) {
					if (this.receipts.read(input.reviewId)?.state === "committing" || error instanceof SessionConsolidationError) throw error;
					throw new SessionConsolidationRunError("commit-failed", "consolidation commit failed before durable intent");
				}
			} catch (error) {
				const current = this.receipts.read(input.reviewId);
				if (current?.state === "committing") throw error;
				const state = classifyFailure(error, signal);
				this.debug?.failure(debugIdentity, `runner-${state}`, error);
				const receipt = createFailedConsolidationReceipt({
					input,
					attempt,
					workerSessionId,
					workerConfig,
					state
				}, this.receipts.timestamp(), current ?? existing);
				this.receipts.write(receipt);
				return {
					outcome: state,
					recovered: false,
					receipt
				};
			}
		});
	}
	recoverPending(pending, signal) {
		return this.receipts.withReviewLock(pending.reviewId, async () => {
			signal?.throwIfAborted();
			const receipt = this.receipts.read(pending.reviewId);
			if (receipt === void 0) throw new SessionConsolidationRunError("pending-recovery", "pending receipt disappeared");
			if (receipt.state === "committed" || receipt.state === "no-change" || receipt.state === "target-conflict") return {
				outcome: receipt.state,
				recovered: true,
				receipt
			};
			if (receipt.state !== "committing") throw new SessionConsolidationRunError("pending-recovery", "pending receipt changed to a non-recoverable state");
			const attempt = receipt.attempts.at(-1);
			if (attempt?.workerSessionId === void 0 || attempt.workerSessionId === null) throw new SessionConsolidationRunError("pending-recovery", "committing receipt has no worker Session");
			try {
				const target = this.memory.workspaceTargetForKey(receipt.workspaceKey);
				const workspace = await this.memory.readWorkspace(target);
				const plan = await this.replay.loadRecoveryPlan(attempt.workerSessionId, receipt, workspace, signal);
				const result = await this.commits.recoverReceiptWithinReviewLock(receipt, target, plan);
				if (result.outcome === "committed" || result.outcome === "no-change") this.settleCandidates(receipt.workspaceKey, plan);
				return result;
			} catch (error) {
				if (signal?.aborted) throw error;
				if (this.receipts.read(pending.reviewId)?.state !== "committing") throw error;
				this.debug?.failure({
					reviewId: receipt.reviewId,
					attempt: attempt.attempt
				}, "recovery-failed", error);
				const attempts = receipt.attempts.map((entry, index) => index === receipt.attempts.length - 1 ? {
					...entry,
					status: "internal-error"
				} : entry);
				const converged = {
					...receipt,
					state: "internal-error",
					completedAt: this.receipts.timestamp(),
					attempts
				};
				this.receipts.write(converged);
				return {
					outcome: "internal-error",
					recovered: false,
					receipt: converged
				};
			}
		});
	}
	settleCandidates(workspaceKey, plan, inputPendingCandidates) {
		if (this.candidatePool === void 0) return;
		try {
			if (plan.parked !== void 0 && plan.parked.length > 0) this.candidatePool.park(workspaceKey, plan.parked);
			if (inputPendingCandidates !== void 0 && inputPendingCandidates.length > 0) this.candidatePool.remove(workspaceKey, inputPendingCandidates.map((c) => c.id));
		} catch (cause) {
			console.warn(`[dsh-memory] failed to settle candidate pool for ${workspaceKey}:`, cause);
		}
	}
};
var SessionConsolidationRunError = class extends Error {
	code;
	constructor(code, message) {
		super(message);
		this.code = code;
		this.name = "SessionConsolidationRunError";
	}
};
/**
* True when `produced` is the segment-0 worker Session id of this
* review/attempt or one of its `-seg-N` siblings. Segment ids are derived from
* the same review id, so prefix equality with a segment suffix is the exact
* contract; anything else is a real mismatch.
*/
function isWorkerSessionOf(produced, base) {
	if (produced === base) return true;
	const prefix = `${base}-seg-`;
	if (!produced.startsWith(prefix)) return false;
	const suffix = produced.slice(prefix.length);
	return /^[1-9][0-9]*$/u.test(suffix);
}
function nextAttempt(receipt) {
	const latest = receipt?.attempts.at(-1)?.attempt ?? 0;
	if (!Number.isSafeInteger(latest) || latest < 0 || latest >= Number.MAX_SAFE_INTEGER) throw new SessionConsolidationRunError("worker-mismatch", "receipt attempt history is invalid");
	return latest + 1;
}
function classifyFailure(error, signal) {
	if (signal?.aborted || error instanceof DOMException && error.name === "AbortError") return "cancelled";
	if (error instanceof ConsolidationWorkerError && error.code === "output-truncated") return "output-truncated";
	if (error instanceof ConsolidationProposalError || error instanceof ConsolidationWorkerError) return "invalid-proposal";
	if (error instanceof SessionConsolidationError) return "source-changed";
	if (error instanceof SessionConsolidationRunError || error instanceof ConsolidationWorkerRuntimeError) return "internal-error";
	if (error instanceof ConsolidationProviderError) return "provider-failed";
	if (error instanceof ConsolidationEvidenceTooLargeError) return "evidence-too-large";
	return "internal-error";
}
