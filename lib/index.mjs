const SETTINGS_FORMAT = 2;
const DREAM_MODES = [
	"off",
	"shadow",
	"manual"
];
/** Plugin-owned settings file; memory Markdown remains the only authoritative memory data. */
var ConsolidationSettingsStore = class {
	defaults;
	path;
	constructor(root, defaults) {
		this.defaults = defaults;
		this.path = join(root, "settings.yml");
	}
	read() {
		let settings;
		if (!existsSync(this.path)) settings = this.fallbackSettings();
		else try {
			settings = parseSettings(readFileSync(this.path, "utf8"));
		} catch (error) {
			const message = error instanceof Error ? error.message : String(error);
			console.warn(`[dsh-memory] ignoring unreadable consolidation settings ${this.path}: ${message}`);
			settings = this.fallbackSettings();
		}
		return {
			...settings,
			revision: settingsRevision(settings)
		};
	}
	fallbackSettings() {
		return {
			selection: validateSelection(this.defaults),
			debugEnabled: false,
			dedupe: "merge",
			writeGate: "on",
			forgetting: "shadow",
			dream: "shadow"
		};
	}
	commit(input) {
		const current = this.read();
		if (current.revision !== input.expectedRevision) return {
			status: "conflict",
			currentRevision: current.revision
		};
		const settings = {
			selection: validateSelection(input.selection),
			debugEnabled: validateDebugEnabled(input.debugEnabled),
			dedupe: input.dedupe === void 0 ? current.dedupe : coerceDedupeModeStrict(input.dedupe),
			writeGate: input.writeGate === void 0 ? current.writeGate : coerceWriteGateStrict(input.writeGate),
			forgetting: input.forgetting === void 0 ? current.forgetting : coerceForgettingStrict(input.forgetting),
			dream: input.dream === void 0 ? current.dream : coerceDreamStrict(input.dream)
		};
		mkdirSync(dirname(this.path), { recursive: true });
		const temporary = `${this.path}.tmp-${process.pid}-${randomUUID()}`;
		writeFileSync(temporary, serializeSettings(settings), {
			encoding: "utf8",
			mode: 384
		});
		renameSync(temporary, this.path);
		return {
			status: "committed",
			revision: settingsRevision(settings)
		};
	}
};
