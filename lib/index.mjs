function parseWorkspaceRecord$1(filename, source) {
	const normalized = normalizeMarkdown(source);
	if (!normalized.startsWith("---\n")) throw new MemoryValidationError(`${filename}: missing YAML frontmatter`);
	const end = normalized.indexOf("\n---\n", 4);
	if (end < 0) throw new MemoryValidationError(`${filename}: unterminated YAML frontmatter`);
	const raw = parse(normalized.slice(4, end));
	if (raw === null || typeof raw !== "object" || Array.isArray(raw)) throw new MemoryValidationError(`${filename}: frontmatter must be an object`);
	const frontmatter = raw;
	requireKeys(frontmatter, [
		"name",
		"description",
		"metadata"
	], `${filename} frontmatter`);
	const metadata = frontmatter.metadata;
	if (metadata === null || typeof metadata !== "object" || Array.isArray(metadata)) throw new MemoryValidationError(`${filename}: metadata must be an object`);
	requireKeys(metadata, ["type"], `${filename} metadata`);
	const record = {
		name: String(frontmatter.name),
		description: String(frontmatter.description),
		type: String(metadata.type),
		content: normalizeMarkdown(normalized.slice(end + 5).replace(/^\n/u, ""))
	};
	validateRecord(record);
	if (filename !== `${record.name}.md`) throw new MemoryValidationError(`${filename}: filename must match frontmatter name ${record.name}`);
	return record;
}
function serializeWorkspaceRecord(record) {
	validateRecord(record);
	return `---\n${stringify({
		name: record.name,
		description: record.description,
		metadata: { type: record.type }
	}).trimEnd()}\n---\n\n${normalizeMarkdown(record.content)}`;
}
function normalizeWorkspaceRecord(record) {
	return {
		...record,
		content: normalizeMarkdown(record.content)
	};
}
function sameWorkspaceRecords(left, right) {
	if (left.length !== right.length) return false;
	return [...left].map(normalizeWorkspaceRecord).sort((a, b) => a.name.localeCompare(b.name, "en")).every((record, index) => {
		const candidate = right[index];
		return candidate !== void 0 && record.name === candidate.name && record.description === candidate.description && record.type === candidate.type && record.content === candidate.content;
	});
}
function renderIndex(records) {
	const rows = [...records].sort((left, right) => left.name.localeCompare(right.name, "en")).map((record) => `- [${record.name}](${record.name}.md) — ${record.description}`);
	return `${GENERATED_INDEX_HEADER}\n${rows.length === 0 ? "" : `\n${rows.join("\n")}\n`}`;
}
function validateRecord(record) {
	validateName(record.name);
	if (record.description.trim() === "" || /[\r\n]/u.test(record.description)) throw new MemoryValidationError("workspace memory description must be a non-empty single line");
	if (![
		"feedback",
		"project",
		"reference"
	].includes(record.type)) throw new MemoryValidationError(`unsupported workspace memory type: ${record.type}`);
	if (record.content.trim() === "") throw new MemoryValidationError("workspace memory content must not be empty");
}
function validateWorkspaceChanges(changes) {
	if (changes.length === 0) throw new MemoryValidationError("workspace changes must not be empty");
	const deletes = /* @__PURE__ */ new Set();
	const puts = /* @__PURE__ */ new Set();
	let reachedPuts = false;
	for (const change of changes) if (change.action === "delete") {
		if (reachedPuts) throw new MemoryValidationError("workspace deletes must precede puts");
		validateName(change.name);
		if (deletes.has(change.name)) throw new MemoryValidationError(`duplicate workspace delete: ${change.name}`);
		deletes.add(change.name);
	} else {
		reachedPuts = true;
		validateRecord(change.record);
		if (puts.has(change.record.name)) throw new MemoryValidationError(`duplicate workspace put: ${change.record.name}`);
		puts.add(change.record.name);
	}
}
function validateName(name) {
	if (`${name}.md`.toLowerCase() === INDEX_FILENAME.toLowerCase()) throw new MemoryValidationError("workspace memory name \"memory\" is reserved for the generated MEMORY.md index; choose a descriptive name");
	if (!NAME_PATTERN.test(name)) throw new MemoryValidationError(`workspace memory name must be kebab-case: ${name}`);
}
function requireKeys(record, keys, label) {
	const actual = Object.keys(record).sort();
	const expected = [...keys].sort();
	if (actual.length !== expected.length || actual.some((key, index) => key !== expected[index])) throw new MemoryValidationError(`${label} must contain exactly: ${expected.join(", ")}`);
}
function workspaceRevision(files) {
	const hash = createHash("sha256");
	for (const [filename, content] of [...files].sort(([left], [right]) => left.localeCompare(right, "en"))) {
		const nameBytes = Buffer.from(filename, "utf8");
		const contentBytes = Buffer.from(content, "utf8");
		const prefix = Buffer.allocUnsafe(8);
		prefix.writeUInt32BE(nameBytes.length, 0);
		prefix.writeUInt32BE(contentBytes.length, 4);
		hash.update(prefix).update(nameBytes).update(contentBytes);
	}
	return `sha256:${hash.digest("hex")}`;
}
function workspaceIdOf(key) {
	return `workspace:${createHash("sha256").update("dsh-memory-workspace-id\0").update(key).digest("hex")}`;
}
function revisionOf(content) {
	return `sha256:${createHash("sha256").update(content, "utf8").digest("hex")}`;
}
function normalizeMarkdown(content) {
	return `${content.replace(/[\r\n]+$/u, "")}\n`;
}
function atomicWrite$1(path, content) {
	mkdirSync(dirname(path), { recursive: true });
	const temporary = `${path}.tmp-${randomUUID()}`;
	writeFileSync(temporary, normalizeMarkdown(content), "utf8");
	renameSync(temporary, path);
}
function slugify(value) {
	const slug = value.toLowerCase().replace(/[^a-z0-9]+/gu, "-").replace(/^-|-$/gu, "");
	return slug === "" ? "workspace" : slug;
}
