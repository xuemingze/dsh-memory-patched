/**
* Locate `<profile>/.dsh/memory` when this bundle lives inside a profile's
* node_modules: profile-installed copies sit at
* `<dsh-home>/profiles/<name>/node_modules/<pkg>/lib/index.mjs`, so walking up
* to the `node_modules` ancestor yields the profile directory that owns the
* durable library. Desktop hosts normally do not set process-level `DSH_HOME`,
* but external launchers can, so this anchor is checked before it.
*/
function profileAdjacentMemoryRoot(moduleUrl) {
	if (!moduleUrl.startsWith("file:")) return void 0;
	let dir = dirname(fileURLToPath(moduleUrl));
	for (let hop = 0; hop < 10; hop += 1) {
		const parent = dirname(dir);
		if (basename(parent) === "node_modules") {
			const candidate = join(dirname(parent), ".dsh", "memory");
			return existsSync(candidate) ? candidate : void 0;
		}
		dir = parent;
	}
}
/** Resolve the durable memory root for this installation. */
function defaultMemoryRoot() {
	const adjacent = profileAdjacentMemoryRoot(import.meta.url);
	if (adjacent !== void 0) return adjacent;
	const configured = process.env.DSH_HOME?.trim();
	if (configured !== void 0 && configured !== "") return join(resolve(configured), "memory");
	const candidates = [
		process.env.HOME,
		process.env.USERPROFILE,
		homedir()
	].filter((home) => typeof home === "string" && home.trim() !== "");
	for (const home of candidates) {
		const candidate = join(home, ".dsh", "memory");
		if (existsSync(candidate)) return candidate;
	}
	return join(candidates[0] ?? homedir(), ".dsh", "memory");
}
function publishWorkspace(directory, records) {
	mkdirSync(dirname(directory), { recursive: true });
	const staging = `${directory}.stage-${randomUUID()}`;
	const backup = `${directory}.backup`;
	mkdirSync(staging);
	try {
		for (const record of records) writeFileSync(join(staging, `${record.name}.md`), serializeWorkspaceRecord(record), "utf8");
		writeFileSync(join(staging, INDEX_FILENAME), renderIndex(records), "utf8");
		if (existsSync(backup)) rmSync(backup, {
			recursive: true,
			force: true
		});
		if (existsSync(directory)) renameSync(directory, backup);
		try {
			renameSync(staging, directory);
		} catch (error) {
			if (existsSync(backup) && !existsSync(directory)) renameSync(backup, directory);
			throw error;
		}
		rmSync(backup, {
			recursive: true,
			force: true
		});
	} finally {
		rmSync(staging, {
			recursive: true,
			force: true
		});
	}
}
