const DAY$1 = 864e5;
/** Working memory cools after this long without evidence or use. */
const WORKING_COOL_AFTER_MS = 60 * DAY$1;
/** Cooled working memory archives after this much additional silence. */
const WORKING_ARCHIVE_AFTER_MS = 120 * DAY$1;
/** Transient memory cools quickly; it described a moment, not a rule. */
const TRANSIENT_COOL_AFTER_MS = 7 * DAY$1;
const TRANSIENT_ARCHIVE_AFTER_MS = 30 * DAY$1;
/** Decide the next lifecycle state for one claim. */
function nextLifecycle(input) {
	if (input.importanceClass === "critical") return {
		lifecycle: "active",
		visible: true,
		reason: "protected"
	};
	if (input.superseded) return {
		lifecycle: "superseded",
		visible: false,
		reason: "superseded"
	};
	const silence = input.now - lastActivity(input);
	if (input.lifecycle === "archived" || input.lifecycle === "cooled") {
		if (silence < coolThreshold(input)) return {
			lifecycle: "active",
			visible: true,
			reason: "restored"
		};
	}
	if (input.lifecycle === "archived") return {
		lifecycle: "archived",
		visible: false,
		reason: "archived"
	};
	if (input.isIncident === true && !input.hasExtractedSop && input.lifecycle === "cooled") {
		if (silence < 5184e6) return {
			lifecycle: "cooled",
			visible: true,
			reason: "awaiting-sop"
		};
	}
	if (input.lifecycle === "cooled") {
		if (silence >= archiveThreshold(input)) return {
			lifecycle: "archived",
			visible: false,
			reason: "archived"
		};
		return {
			lifecycle: "cooled",
			visible: true,
			reason: "cooled"
		};
	}
	if (silence < coolThreshold(input)) return {
		lifecycle: "active",
		visible: true,
		reason: "fresh"
	};
	if (input.importanceClass === "durable") return {
		lifecycle: "active",
		visible: true,
		reason: "review"
	};
	return {
		lifecycle: "cooled",
		visible: true,
		reason: "cooled"
	};
}
/** Evidence or actual use, whichever is more recent. */
function lastActivity(input) {
	if (input.lastUsedAt === null) return input.lastEvidenceAt;
	return Math.max(input.lastEvidenceAt, input.lastUsedAt);
}
function coolThreshold(input) {
	if (input.importanceClass === "transient" || input.volatility === "transient") return TRANSIENT_COOL_AFTER_MS;
	return WORKING_COOL_AFTER_MS;
}
function archiveThreshold(input) {
	if (input.importanceClass === "transient" || input.volatility === "transient") return TRANSIENT_ARCHIVE_AFTER_MS;
	return WORKING_ARCHIVE_AFTER_MS;
}
