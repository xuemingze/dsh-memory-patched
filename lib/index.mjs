function parseWorkspaceRecord$1(filename, source) {
	const normalized = normalizeMarkdown(source.replace(/\r\n/gu, "\n"));
	if (!normalized.startsWith("---\n")) throw new MemoryValidationError(`${filename}: missing YAML frontmatter`);
	const end = normalized.indexOf("\n---\n", 4);
	if (end < 0) throw new MemoryValidationError(`${filename}: unterminated YAML frontmatter`);
	const raw = parse(normalized.slice(4, end));
	if (raw === null || typeof raw !== "object" || Array.isArray(raw)) throw new MemoryValidationError(`${filename}: frontmatter must be an object`);
	const frontmatter = raw;
	requireKeys(frontmatter, [
		"name",
		"description",
		"metadata"
	], `${filename} frontmatter`);
	const metadata = frontmatter.metadata;
	if (metadata === null || typeof metadata !== "object" || Array.isArray(metadata)) throw new MemoryValidationError(`${filename}: metadata must be an object`);
	const metadataRecord = metadata;
	const metadataKeys = Object.keys(metadataRecord).sort();
	if (!(metadataKeys.length === 1 && metadataKeys[0] === "type" || metadataKeys.length === 2 && metadataKeys[0] === "lastEvidenceTime" && metadataKeys[1] === "type")) throw new MemoryValidationError(`${filename} metadata must contain type and optionally lastEvidenceTime`);
	const lastEvidenceTimeRaw = metadataRecord.lastEvidenceTime;
	const record = {
		name: String(frontmatter.name),
		description: String(frontmatter.description),
		type: String(metadata.type),
		content: normalizeMarkdown(normalized.slice(end + 5).replace(/^\n/u, "")),
		...typeof lastEvidenceTimeRaw === "number" && Number.isFinite(lastEvidenceTimeRaw) ? { lastEvidenceTime: lastEvidenceTimeRaw } : {}
	};
	validateRecord(record);
	if (filename !== `${record.name}.md`) throw new MemoryValidationError(`${filename}: filename must match frontmatter name ${record.name}`);
	return record;
}
