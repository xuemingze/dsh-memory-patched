/**
* Drive one Dream run through a scoped agent.
*
* The worker is restricted to a single tool and given no other capability: it
* cannot read files, run shell, or reach the network. Everything it decides
* arrives through one validated channel.
*/
async function runDreamWithAgent(options) {
	const prompt = renderDreamPrompt(options.context);
	let accepted;
	let attempts = 0;
	let lastRejection = "";
	let agentError;
	const handle = await options.agents.create({
		sessionId: options.sessionId,
		meta: { cwd: options.cwd },
		agentOptions: options.config,
		...options.signal === void 0 ? {} : { signal: options.signal },
		setup: (scope) => {
			scope.systemPrompt.suppressRuntimeContext();
			scope.tools.restrict({ allow: [DREAM_PROPOSAL_TOOL] });
			scope.tools.register(defineDreamTool((value) => {
				attempts += 1;
				const result = options.validate(value);
				if (result.accepted) accepted = value;
				else lastRejection = result.message;
				return {
					accepted: result.accepted,
					message: result.accepted ? "Plan accepted." : `Plan rejected: ${result.message}. Correct it and submit again.`
				};
			}));
			scope.on("agent/error", (payload) => {
				agentError = payload.error;
			});
		}
	});
	try {
		handle.agent.inject({
			role: "user",
			content: prompt
		});
		handle.agent.followup({
			role: "user",
			content: "Submit the plan now by calling the tool."
		});
		await handle.agent.whenIdle();
	} catch (cause) {
		if (agentError !== void 0) throw new DreamAgentWorkerError("provider-failed", agentError instanceof Error ? agentError.message : String(agentError), { cause });
		throw cause;
	} finally {
		await handle.dispose();
	}
	if (accepted === void 0) throw new DreamAgentWorkerError("missing-proposal", attempts === 0 ? "Dream worker never called the proposal tool" : `Dream made ${attempts} attempts without a valid plan; last rejection: ${lastRejection}`);
	return {
		workerSessionId: handle.agent.session.id,
		submission: accepted,
		attempts
	};
}
/** Wrap the handler in whatever shape the host tool registrar expects. */
function defineDreamTool(submit) {
	return {
		...dreamProposalTool(),
		handler: async (input) => submit(input)
	};
}
