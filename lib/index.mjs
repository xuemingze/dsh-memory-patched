function publishWorkspace(directory, records) {
	mkdirSync(dirname(directory), { recursive: true });
	const staging = `${directory}.stage-${randomUUID()}`;
	const backup = `${directory}.backup`;
	mkdirSync(staging);
	try {
		for (const record of records) writeFileSync(join(staging, `${record.name}.md`), serializeWorkspaceRecord(record), "utf8");
		writeFileSync(join(staging, INDEX_FILENAME), renderIndex(records), "utf8");
		if (existsSync(backup)) rmSync(backup, {
			recursive: true,
			force: true
		});
		if (existsSync(directory)) renameSync(directory, backup);
		try {
			renameSync(staging, directory);
		} catch (error) {
			if (existsSync(backup) && !existsSync(directory)) renameSync(backup, directory);
			throw error;
		}
		rmSync(backup, {
			recursive: true,
			force: true
		});
	} finally {
		rmSync(staging, {
			recursive: true,
			force: true
		});
	}
}
