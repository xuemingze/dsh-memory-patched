/** Apply and validate one batch using the exact generation algorithm used by commit. */
function previewWorkspaceChanges(current, changes) {
	validateWorkspaceChanges(changes);
	const next = /* @__PURE__ */ new Map();
	for (const record of current.records) {
		validateRecord(record);
		if (next.has(record.name)) throw new MemoryValidationError(`duplicate workspace memory: ${record.name}`);
		next.set(record.name, normalizeWorkspaceRecord(record));
	}
	for (const change of changes) if (change.action === "put") next.set(change.record.name, normalizeWorkspaceRecord(change.record));
	else if (!next.delete(change.name)) throw new MemoryValidationError(`workspace memory does not exist: ${change.name}`);
	const records = [...next.values()].sort((left, right) => left.name.localeCompare(right.name, "en"));
	const index = renderIndex(records);
	const changed = !sameWorkspaceRecords(current.records, records);
	return {
		records,
		index,
		revision: changed ? workspaceRevision(records.map((record) => [`${record.name}.md`, serializeWorkspaceRecord(record)])) : current.revision,
		changed
	};
}
function readWorkspaceDirectory(requestedDirectory) {
	const directory = readableWorkspaceDirectory(requestedDirectory);
	if (directory === void 0) return emptyWorkspaceView();
	const sources = readdirSync(directory, { withFileTypes: true }).filter((entry) => entry.isFile() && entry.name.endsWith(".md") && entry.name !== INDEX_FILENAME).map((entry) => entry.name).sort().map((filename) => [filename, normalizeMarkdown(readFileSync(join(directory, filename), "utf8"))]);
	const records = sources.map(([filename, source]) => parseWorkspaceRecord$1(filename, source));
	return {
		records,
		index: renderIndex(records),
		revision: workspaceRevision(sources)
	};
}
