/** Markdown-backed MemoryStore Service Provider. */

import { createHash, randomUUID } from 'node:crypto'
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  renameSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { basename, dirname, isAbsolute, join, resolve } from 'node:path'
import { Context, Service } from '@deepseek-ai/cordis'
import { parse, stringify } from 'yaml'
import type {
  MemoryRevision,
  MemoryStatus,
  WorkspaceId,
  WorkspaceListResponse,
  WorkspaceReadResponse,
} from './protocol.ts'

const GLOBAL_FILENAME = 'GLOBAL.md'
const INDEX_FILENAME = 'MEMORY.md'
const NAME_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/
const WORKSPACE_KEY_PATTERN = /^([\p{L}\p{N}]+(?:-[\p{L}\p{N}]+)*)-([a-f0-9]{16})$/u
const GENERATED_INDEX_HEADER = '<!-- Generated by dsh-memory. Do not edit directly. -->'
const DEFAULT_GLOBAL = `# Global Memory

## User Profile

## User Preferences

## General Tips
`

/** Allowed Workspace record categories. */
export type WorkspaceMemoryType = 'feedback' | 'project' | 'reference'

/** Host-authoritative current Workspace identity. */
export interface WorkspaceScope {
  readonly cwd: string
  readonly key: string
  readonly directory: string
}

/** Host-only Workspace location that does not require retaining or exposing cwd. */
export interface WorkspaceTarget {
  readonly key: string
  readonly directory: string
}

/** Parsed Workspace memory record. */
export interface WorkspaceMemory {
  readonly name: string
  readonly description: string
  readonly type: WorkspaceMemoryType
  readonly content: string
}

/** Complete Workspace view and its derived index. */
export interface WorkspaceMemoryView {
  readonly records: readonly WorkspaceMemory[]
  readonly index: string
  readonly revision: MemoryRevision
}

/** Deterministic result of applying a Workspace batch without publishing it. */
export interface WorkspaceMemoryPreview extends WorkspaceMemoryView {
  readonly changed: boolean
}

export interface GlobalMemoryView {
  readonly content: string
  readonly revision: MemoryRevision
}

export interface GlobalMemoryPreview extends GlobalMemoryView {
  readonly changed: boolean
}

/** Model-visible prompt text paired with Host-only generations observed while rendering it. */
export interface MemoryContextSnapshot {
  readonly text: string
  readonly globalRevision: MemoryRevision
  readonly workspace?: {
    readonly key: string
    readonly revision: MemoryRevision
  }
}

/** One atomic Workspace mutation. */
export type WorkspaceMemoryChange =
  | { readonly action: 'put'; readonly record: WorkspaceMemory }
  | { readonly action: 'delete'; readonly name: string }

/** Successful commit information returned to Consumers. */
export interface MemoryCommitResult {
  readonly operation: 'create' | 'update' | 'delete'
  readonly revision: MemoryRevision
}

/** Raised when a compare-and-swap write observes a newer revision. */
export class MemoryConflictError extends Error {
  constructor(readonly currentRevision: MemoryRevision) {
    super(`memory revision changed; current revision is ${currentRevision}`)
    this.name = 'MemoryConflictError'
  }
}

/** Raised when a Markdown record violates the durable format. */
export class MemoryValidationError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'MemoryValidationError'
  }
}

/**
 * Markdown implementation of the Host MemoryStore service.
 *
 * Global commits publish one renamed file. Workspace commits build a complete
 * sibling directory and swap it under a per-scope lock, so readers never
 * observe a generated index from a different record set through this service.
 */
export class MarkdownMemoryStore extends Service {
  private readonly locks = new Map<string, Promise<void>>()

  constructor(ctx: Context, readonly root: string = defaultMemoryRoot()) {
    super(ctx, 'memoryStore')
  }

  /** Create the stable root and default global document if absent. */
  initialize(): void {
    mkdirSync(join(this.root, 'workspaces'), { recursive: true })
    const globalPath = join(this.root, GLOBAL_FILENAME)
    if (!existsSync(globalPath)) atomicWrite(globalPath, DEFAULT_GLOBAL)
  }

  /** Resolve one absolute cwd into the v0.1 lexical Workspace identity. */
  scopeForCwd(cwd: string): WorkspaceScope {
    if (!isAbsolute(cwd)) throw new MemoryValidationError(`workspace cwd must be absolute: ${cwd}`)
    const normalized = resolve(cwd)
    const slug = slugify(basename(normalized))
    const digest = createHash('sha256').update(normalized).digest('hex').slice(0, 16)
    const key = `${slug}-${digest}`
    return { cwd: normalized, key, directory: join(this.root, 'workspaces', key) }
  }

  /** Return the Browser-safe display label for a resolvable Workspace cwd. */
  workspaceDisplayNameForCwd(cwd: string): string {
    const scope = this.scopeForCwd(cwd)
    const match = WORKSPACE_KEY_PATTERN.exec(scope.key)
    if (match?.[1] === undefined) throw new MemoryValidationError(`cannot derive Workspace display name: ${cwd}`)
    return match[1]
  }

  /** Return the opaque Browser identity and display label for one resolvable Workspace cwd. */
  workspaceReferenceForCwd(cwd: string): { workspaceId: WorkspaceId; displayName: string } {
    const scope = this.scopeForCwd(cwd)
    const match = WORKSPACE_KEY_PATTERN.exec(scope.key)
    if (match?.[1] === undefined) throw new MemoryValidationError(`cannot derive Workspace display name: ${cwd}`)
    return { workspaceId: workspaceIdOf(scope.key), displayName: match[1] }
  }

  /** Resolve one receipt-owned Workspace key without accepting an arbitrary path. */
  workspaceTargetForKey(key: string): WorkspaceTarget {
    if (!WORKSPACE_KEY_PATTERN.test(key)) throw new MemoryValidationError(`invalid Workspace key: ${key}`)
    return { key, directory: join(this.root, 'workspaces', key) }
  }

  /** Read the authoritative global document. */
  async readGlobal(): Promise<{ content: string; revision: MemoryRevision }> {
    return this.readGlobalSync()
  }

  /** Synchronous prompt-assembly view of the authoritative global document. */
  readGlobalSync(): { content: string; revision: MemoryRevision } {
    this.initialize()
    const content = normalizeMarkdown(readFileSync(join(this.root, GLOBAL_FILENAME), 'utf8'))
    return { content, revision: revisionOf(content) }
  }

  /** Replace GLOBAL.md when the caller still holds its latest revision. */
  async commitGlobal(input: {
    expectedRevision: MemoryRevision
    content: string
  }): Promise<MemoryCommitResult> {
    return this.withLock('global', async () => {
      const current = this.readGlobalSync()
      if (current.revision !== input.expectedRevision) throw new MemoryConflictError(current.revision)
      const content = normalizeMarkdown(input.content)
      atomicWrite(join(this.root, GLOBAL_FILENAME), content)
      return { operation: 'update', revision: revisionOf(content) }
    })
  }

  /** Read and validate all records in one Workspace. */
  async readWorkspace(scope: Pick<WorkspaceTarget, 'directory'>): Promise<WorkspaceMemoryView> {
    return this.readWorkspaceSync(scope)
  }

  /** Synchronous Workspace view used during prompt assembly. */
  readWorkspaceSync(scope: Pick<WorkspaceTarget, 'directory'>): WorkspaceMemoryView {
    return readWorkspaceDirectory(scope.directory)
  }

  /** Enumerate Browser-safe summaries for every valid Workspace directory. */
  listWorkspaces(): WorkspaceListResponse {
    const workspaces = this.discoverWorkspaces().map((workspace) => {
      const view = readWorkspaceDirectory(workspace.directory)
      return {
        workspaceId: workspace.workspaceId,
        displayName: workspace.displayName,
        revision: view.revision,
        recordCount: view.records.length,
      }
    })
    return { workspaces }
  }

  /** Resolve and read one Workspace only through its opaque Browser id. */
  readWorkspaceById(workspaceId: WorkspaceId): WorkspaceReadResponse | undefined {
    const workspace = this.discoverWorkspaces().find(entry => entry.workspaceId === workspaceId)
    if (workspace === undefined) return
    const view = readWorkspaceDirectory(workspace.directory)
    return {
      workspaceId: workspace.workspaceId,
      displayName: workspace.displayName,
      revision: view.revision,
      recordCount: view.records.length,
      index: view.index,
      records: view.records.map(record => ({ ...record })),
    }
  }

  private discoverWorkspaces(): Array<{
    workspaceId: WorkspaceId
    displayName: string
    key: string
    directory: string
  }> {
    this.initialize()
    const workspacesRoot = join(this.root, 'workspaces')
    return readdirSync(workspacesRoot, { withFileTypes: true })
      .filter(entry => entry.isDirectory())
      .flatMap((entry) => {
        const match = WORKSPACE_KEY_PATTERN.exec(entry.name)
        if (match === null || match[1] === undefined) return []
        return [{
          workspaceId: workspaceIdOf(entry.name),
          displayName: match[1],
          key: entry.name,
          directory: join(workspacesRoot, entry.name),
        }]
      })
      .sort((left, right) => {
        const byName = left.displayName.localeCompare(right.displayName, 'en')
        return byName === 0 ? left.workspaceId.localeCompare(right.workspaceId, 'en') : byName
      })
  }

  /** Apply a revision-checked record batch and publish one new Workspace generation. */
  async commitWorkspace(input: {
    scope: WorkspaceTarget
    expectedRevision: MemoryRevision
    changes: readonly WorkspaceMemoryChange[]
  }): Promise<MemoryCommitResult> {
    return this.commitWorkspaceAt(input.scope.key, input.scope.directory, input.expectedRevision, input.changes)
  }

  /** Resolve and commit one Browser batch only through its opaque Workspace id. */
  async commitWorkspaceById(input: {
    workspaceId: WorkspaceId
    expectedRevision: MemoryRevision
    changes: readonly WorkspaceMemoryChange[]
  }): Promise<MemoryCommitResult | undefined> {
    const workspace = this.discoverWorkspaces().find(entry => entry.workspaceId === input.workspaceId)
    if (workspace === undefined) return
    return this.commitWorkspaceAt(workspace.key, workspace.directory, input.expectedRevision, input.changes)
  }

  private async commitWorkspaceAt(
    key: string,
    directory: string,
    expectedRevision: MemoryRevision,
    changes: readonly WorkspaceMemoryChange[],
  ): Promise<MemoryCommitResult> {
    validateWorkspaceChanges(changes)
    return this.withLock(`workspace:${key}`, async () => {
      const current = readWorkspaceDirectory(directory)
      if (current.revision !== expectedRevision) throw new MemoryConflictError(current.revision)
      let operation: MemoryCommitResult['operation'] = 'update'
      if (changes.length === 1) {
        const change = changes[0]!
        operation = change.action === 'delete'
          ? 'delete'
          : current.records.some(record => record.name === change.record.name) ? 'update' : 'create'
      }
      const preview = previewWorkspaceChanges(current, changes)
      if (preview.changed) publishWorkspace(directory, preview.records)
      return { operation, revision: preview.revision }
    })
  }

  /** Render the complete runtime-context snapshot for one optional cwd. */
  renderContext(cwd?: string): string {
    return this.renderContextSnapshot(cwd).text
  }

  /** Render model-visible memory and retain its exact generations for Host-owned CAS. */
  renderContextSnapshot(cwd?: string): MemoryContextSnapshot {
    const global = this.readGlobalSync()
    const sections = [
      '## Memory Context',
      '',
      '### Global Memory',
      '',
      global.content.trimEnd(),
    ]
    let observedWorkspace: MemoryContextSnapshot['workspace']
    if (cwd !== undefined) {
      const scope = this.scopeForCwd(cwd)
      const workspace = this.readWorkspaceSync(scope)
      observedWorkspace = { key: scope.key, revision: workspace.revision }
      sections.push(
        '',
        '### Current Workspace Memory Index',
        '',
        `Detailed memory directory: ${scope.directory}`,
      )
      if (workspace.index.trim() !== '') sections.push('', workspace.index.trimEnd())
    }
    return {
      text: `${sections.join('\n')}\n`,
      globalRevision: global.revision,
      ...(observedWorkspace === undefined ? {} : { workspace: observedWorkspace }),
    }
  }

  /** Collect observational store totals for the Settings status banner. */
  status(): MemoryStatus {
    const global = this.readGlobalSync()
    return {
      enabled: true,
      root: this.root,
      globalBytes: Buffer.byteLength(global.content, 'utf8'),
      workspaceCount: this.discoverWorkspaces().length,
    }
  }

  private async withLock<T>(key: string, body: () => Promise<T>): Promise<T> {
    const previous = this.locks.get(key) ?? Promise.resolve()
    let release: (() => void) | undefined
    const current = new Promise<void>((resolveLock) => { release = resolveLock })
    const queued = previous.then(() => current)
    this.locks.set(key, queued)
    await previous
    try {
      return await body()
    } finally {
      release?.()
      if (this.locks.get(key) === queued) this.locks.delete(key)
    }
  }
}

/** Normalize and preview a complete Global document replacement. */
export function previewGlobalMemory(current: GlobalMemoryView, content: string): GlobalMemoryPreview {
  const normalized = normalizeMarkdown(content)
  const changed = normalized !== current.content
  return {
    content: changed ? normalized : current.content,
    revision: changed ? revisionOf(normalized) : current.revision,
    changed,
  }
}

/** Reconstruct a normalized Global view from replayed model-visible content. */
export function globalMemoryViewOf(content: string): GlobalMemoryView {
  const normalized = normalizeMarkdown(content)
  return { content: normalized, revision: revisionOf(normalized) }
}

/** Reconstruct a Workspace view from replayed model-visible records. */
export function workspaceMemoryViewOf(records: readonly WorkspaceMemory[]): WorkspaceMemoryView {
  const normalized = [...records].map(normalizeWorkspaceRecord)
    .sort((left, right) => left.name.localeCompare(right.name, 'en'))
  for (const record of normalized) validateRecord(record)
  return {
    records: normalized,
    index: renderIndex(normalized),
    revision: workspaceRevision(normalized.map(record => [`${record.name}.md`, serializeWorkspaceRecord(record)])),
  }
}

/** Apply and validate one batch using the exact generation algorithm used by commit. */
export function previewWorkspaceChanges(
  current: WorkspaceMemoryView,
  changes: readonly WorkspaceMemoryChange[],
): WorkspaceMemoryPreview {
  validateWorkspaceChanges(changes)
  const next = new Map<string, WorkspaceMemory>()
  for (const record of current.records) {
    validateRecord(record)
    if (next.has(record.name)) throw new MemoryValidationError(`duplicate workspace memory: ${record.name}`)
    next.set(record.name, normalizeWorkspaceRecord(record))
  }
  for (const change of changes) {
    if (change.action === 'put') {
      next.set(change.record.name, normalizeWorkspaceRecord(change.record))
    } else if (!next.delete(change.name)) {
      throw new MemoryValidationError(`workspace memory does not exist: ${change.name}`)
    }
  }
  const records = [...next.values()].sort((left, right) => left.name.localeCompare(right.name, 'en'))
  const index = renderIndex(records)
  const changed = !sameWorkspaceRecords(current.records, records)
  const revision = changed
    ? workspaceRevision(records.map(record => [`${record.name}.md`, serializeWorkspaceRecord(record)]))
    : current.revision
  return { records, index, revision, changed }
}

function readWorkspaceDirectory(requestedDirectory: string): WorkspaceMemoryView {
  const directory = readableWorkspaceDirectory(requestedDirectory)
  if (directory === undefined) return emptyWorkspaceView()
  const files = readdirSync(directory, { withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith('.md') && entry.name !== INDEX_FILENAME)
    .map(entry => entry.name)
    .sort()
  const sources = files.map(filename => [filename, normalizeMarkdown(readFileSync(join(directory, filename), 'utf8'))] as const)
  const records = sources.map(([filename, source]) => parseWorkspaceRecord(filename, source))
  const index = renderIndex(records)
  return { records, index, revision: workspaceRevision(sources) }
}

/** Resolve `$DSH_HOME/memory`, falling back to `~/.dsh/memory`. */
export function defaultMemoryRoot(): string {
  const configured = process.env.DSH_HOME?.trim()
  const dshHome = configured === undefined || configured === ''
    ? join(process.env.HOME ?? process.cwd(), '.dsh')
    : resolve(configured)
  return join(dshHome, 'memory')
}

function publishWorkspace(directory: string, records: readonly WorkspaceMemory[]): void {
  mkdirSync(dirname(directory), { recursive: true })
  const staging = `${directory}.stage-${randomUUID()}`
  const backup = `${directory}.backup`
  mkdirSync(staging)
  try {
    for (const record of records) {
      writeFileSync(join(staging, `${record.name}.md`), serializeWorkspaceRecord(record), 'utf8')
    }
    writeFileSync(join(staging, INDEX_FILENAME), renderIndex(records), 'utf8')
    if (existsSync(backup)) rmSync(backup, { recursive: true, force: true })
    if (existsSync(directory)) renameSync(directory, backup)
    try {
      renameSync(staging, directory)
    } catch (error: unknown) {
      if (existsSync(backup) && !existsSync(directory)) renameSync(backup, directory)
      throw error
    }
    rmSync(backup, { recursive: true, force: true })
  } finally {
    rmSync(staging, { recursive: true, force: true })
  }
}

function readableWorkspaceDirectory(directory: string): string | undefined {
  if (existsSync(directory)) return directory
  const backup = `${directory}.backup`
  return existsSync(backup) ? backup : undefined
}

function emptyWorkspaceView(): WorkspaceMemoryView {
  return { records: [], index: `${GENERATED_INDEX_HEADER}\n`, revision: workspaceRevision([]) }
}

function parseWorkspaceRecord(filename: string, source: string): WorkspaceMemory {
  const normalized = normalizeMarkdown(source)
  if (!normalized.startsWith('---\n')) throw new MemoryValidationError(`${filename}: missing YAML frontmatter`)
  const end = normalized.indexOf('\n---\n', 4)
  if (end < 0) throw new MemoryValidationError(`${filename}: unterminated YAML frontmatter`)
  const raw = parse(normalized.slice(4, end)) as unknown
  if (raw === null || typeof raw !== 'object' || Array.isArray(raw)) {
    throw new MemoryValidationError(`${filename}: frontmatter must be an object`)
  }
  const frontmatter = raw as Record<string, unknown>
  requireKeys(frontmatter, ['name', 'description', 'metadata'], `${filename} frontmatter`)
  const metadata = frontmatter.metadata
  if (metadata === null || typeof metadata !== 'object' || Array.isArray(metadata)) {
    throw new MemoryValidationError(`${filename}: metadata must be an object`)
  }
  requireKeys(metadata as Record<string, unknown>, ['type'], `${filename} metadata`)
  const record: WorkspaceMemory = {
    name: String(frontmatter.name),
    description: String(frontmatter.description),
    type: String((metadata as Record<string, unknown>).type) as WorkspaceMemoryType,
    content: normalizeMarkdown(normalized.slice(end + 5).replace(/^\n/u, '')),
  }
  validateRecord(record)
  if (filename !== `${record.name}.md`) {
    throw new MemoryValidationError(`${filename}: filename must match frontmatter name ${record.name}`)
  }
  return record
}

function serializeWorkspaceRecord(record: WorkspaceMemory): string {
  validateRecord(record)
  const frontmatter = stringify({
    name: record.name,
    description: record.description,
    metadata: { type: record.type },
  }).trimEnd()
  return `---\n${frontmatter}\n---\n\n${normalizeMarkdown(record.content)}`
}

function normalizeWorkspaceRecord(record: WorkspaceMemory): WorkspaceMemory {
  return { ...record, content: normalizeMarkdown(record.content) }
}

function sameWorkspaceRecords(left: readonly WorkspaceMemory[], right: readonly WorkspaceMemory[]): boolean {
  if (left.length !== right.length) return false
  const normalizedLeft = [...left]
    .map(normalizeWorkspaceRecord)
    .sort((a, b) => a.name.localeCompare(b.name, 'en'))
  return normalizedLeft.every((record, index) => {
    const candidate = right[index]
    return candidate !== undefined
      && record.name === candidate.name
      && record.description === candidate.description
      && record.type === candidate.type
      && record.content === candidate.content
  })
}

function renderIndex(records: readonly WorkspaceMemory[]): string {
  const rows = [...records]
    .sort((left, right) => left.name.localeCompare(right.name, 'en'))
    .map(record => `- [${record.name}](${record.name}.md) — ${record.description}`)
  return `${GENERATED_INDEX_HEADER}\n${rows.length === 0 ? '' : `\n${rows.join('\n')}\n`}`
}

function validateRecord(record: WorkspaceMemory): void {
  validateName(record.name)
  if (record.description.trim() === '' || /[\r\n]/u.test(record.description)) {
    throw new MemoryValidationError('workspace memory description must be a non-empty single line')
  }
  if (!['feedback', 'project', 'reference'].includes(record.type)) {
    throw new MemoryValidationError(`unsupported workspace memory type: ${record.type}`)
  }
  if (record.content.trim() === '') throw new MemoryValidationError('workspace memory content must not be empty')
}

function validateWorkspaceChanges(changes: readonly WorkspaceMemoryChange[]): void {
  if (changes.length === 0) throw new MemoryValidationError('workspace changes must not be empty')
  const deletes = new Set<string>()
  const puts = new Set<string>()
  let reachedPuts = false
  for (const change of changes) {
    if (change.action === 'delete') {
      if (reachedPuts) throw new MemoryValidationError('workspace deletes must precede puts')
      validateName(change.name)
      if (deletes.has(change.name)) throw new MemoryValidationError(`duplicate workspace delete: ${change.name}`)
      deletes.add(change.name)
    } else {
      reachedPuts = true
      validateRecord(change.record)
      if (puts.has(change.record.name)) throw new MemoryValidationError(`duplicate workspace put: ${change.record.name}`)
      puts.add(change.record.name)
    }
  }
}

function validateName(name: string): void {
  if (`${name}.md`.toLowerCase() === INDEX_FILENAME.toLowerCase()) {
    throw new MemoryValidationError('workspace memory name "memory" is reserved for the generated MEMORY.md index; choose a descriptive name')
  }
  if (!NAME_PATTERN.test(name)) throw new MemoryValidationError(`workspace memory name must be kebab-case: ${name}`)
}

function requireKeys(record: Record<string, unknown>, keys: readonly string[], label: string): void {
  const actual = Object.keys(record).sort()
  const expected = [...keys].sort()
  if (actual.length !== expected.length || actual.some((key, index) => key !== expected[index])) {
    throw new MemoryValidationError(`${label} must contain exactly: ${expected.join(', ')}`)
  }
}

function workspaceRevision(files: readonly (readonly [string, string])[]): MemoryRevision {
  const hash = createHash('sha256')
  for (const [filename, content] of [...files].sort(([left], [right]) => left.localeCompare(right, 'en'))) {
    const nameBytes = Buffer.from(filename, 'utf8')
    const contentBytes = Buffer.from(content, 'utf8')
    const prefix = Buffer.allocUnsafe(8)
    prefix.writeUInt32BE(nameBytes.length, 0)
    prefix.writeUInt32BE(contentBytes.length, 4)
    hash.update(prefix).update(nameBytes).update(contentBytes)
  }
  return `sha256:${hash.digest('hex')}` as MemoryRevision
}

function workspaceIdOf(key: string): WorkspaceId {
  const digest = createHash('sha256').update('dsh-memory-workspace-id\0').update(key).digest('hex')
  return `workspace:${digest}` as WorkspaceId
}

function revisionOf(content: string): MemoryRevision {
  return `sha256:${createHash('sha256').update(content, 'utf8').digest('hex')}` as MemoryRevision
}

function normalizeMarkdown(content: string): string {
  return `${content.replace(/[\r\n]+$/u, '')}\n`
}

function atomicWrite(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true })
  const temporary = `${path}.tmp-${randomUUID()}`
  writeFileSync(temporary, normalizeMarkdown(content), 'utf8')
  renameSync(temporary, path)
}

function slugify(value: string): string {
  const slug = value.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-|-$/gu, '')
  return slug === '' ? 'workspace' : slug
}
